    (r"бутончик(?:а)", "колечка"),
    (r"бутончик(?:у)", "колечку"),
    (r"бутончик(?:е)", "колечке"),
    (r"бутончик(?![а-яё])", "колечко"),
    # Pleasure Dial: "ручка" (knob) becomes "регулятор" (dial)
    (r"ручкой удовольствия", "регулятором удовольствия"),
    (r"ручка удовольствия", "регулятор удовольствия"),
