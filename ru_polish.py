DASH = re.compile(r"(?<![А-Яа-яЁё])(" + "|".join(re.escape(s) for s in sorted(SUBJECTS, key=len, reverse=True))
                  + r") это(?= )")

def dash(m):
    subj = m.group(1)
    return f"{subj} — это" if not subj.endswith(",") else f"{subj} — это"


def polish(text):
    for a, b in LIT:
        text = text.replace(a, b)
    for rx, fn in WORDS:
        text = rx.sub(fn, text)
    text = DASH.sub(dash, text)
    return text


def targets():
    t = sorted(glob.glob(os.path.join(HERE, "public", "ru", "**", "*.html"), recursive=True))
    for name in ("langcfg/ru.py", "signup.py", "sidebar.py"):
        p = os.path.join(HERE, name)
        if os.path.exists(p):
            t.append(p)
    return t


def main():
    changed = 0
    for p in targets():
        s = open(p, encoding="utf-8").read()
        n = polish(s)
        if n != s:
            open(p, "w", encoding="utf-8").write(n)
            changed += 1
    print(f"ru_polish: {changed} files changed")


if __name__ == "__main__":
    main()
