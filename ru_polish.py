# ------------------------------------------------------------------ word-level rewrites
def keep_case(repl):
    def f(m):
        s = m.group(0)
        if s.isupper() and len(s) > 1:
            return repl.upper()
        if s[0].isupper():
            return repl[0].upper() + repl[1:]
        return repl
    return f

# (regex, replacement) with case kept. Anus nickname: бутончик -> колечко.
